#!/usr/bin/env python3
"""Turn results/*.csv into results/summary.md and the figure analogues.

  python3 tools/analyze.py            (after tools/run_experiments.sh)

Nothing here is tuned: every number in summary.md is a mean over the ten trials of a CSV row, a ratio
of two such means, or a least-squares slope on log-log axes. Ratios are "allocator / graph coloring",
so a value above 1 means the allocator is slower (compile time) or runs more instructions (code quality).
"""
import csv
import math
import os
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "results")


def load(name):
    rows = []
    with open(os.path.join(RES, name)) as f:
        for r in csv.DictReader(f):
            for k in ("R", "trial", "spills_static", "executed", "cycles", "spill_loads", "spill_stores", "vars", "instrs", "blocks"):
                r[k] = int(r[k])
            for k in ("t_liveness_ns", "t_intervals_ns", "t_setup_ns", "t_alloc_ns"):
                r[k] = float(r[k])
            rows.append(r)
    return rows


def group(rows):
    """(program, allocator, numbering, R) -> dict of means, std of the total, and the static metrics."""
    g = defaultdict(list)
    for r in rows:
        g[(r["program"], r["allocator"], r["numbering"], r["R"])].append(r)
    out = {}
    for key, rs in g.items():
        tot = [r["t_liveness_ns"] + r["t_setup_ns"] + r["t_alloc_ns"] for r in rs]
        out[key] = dict(
            live=np.mean([r["t_liveness_ns"] for r in rs]),
            setup=np.mean([r["t_setup_ns"] for r in rs]),
            alloc=np.mean([r["t_alloc_ns"] for r in rs]),
            total=np.mean(tot),
            total_sd=np.std(tot, ddof=1) if len(tot) > 1 else 0.0,
            spills=rs[0]["spills_static"], executed=rs[0]["executed"], cycles=rs[0]["cycles"],
            loads=rs[0]["spill_loads"], stores=rs[0]["spill_stores"],
            vars=rs[0]["vars"], instrs=rs[0]["instrs"], blocks=rs[0]["blocks"], n=len(rs),
        )
    return out


def us(ns):
    return f"{ns / 1000:.1f}" if ns < 1e6 else f"{ns / 1e6:.2f}ms"


def fmt_t(ns):
    if ns < 1e3:
        return f"{ns:.0f} ns"
    if ns < 1e6:
        return f"{ns / 1e3:.1f} µs"
    return f"{ns / 1e6:.2f} ms"


def slope(xs, ys):
    return float(np.polyfit(np.log(xs), np.log(ys), 1)[0])


def geomean(v):
    v = list(v)
    return math.exp(sum(math.log(x) for x in v) / len(v))


def main():
    out = []
    P = out.append

    # ------------------------------------------------------------------ kernels
    K = group(load("kernels.csv"))
    progs = sorted({k[0] for k in K})
    Rs = sorted({k[3] for k in K})

    P("# Summary of results\n")
    P("Generated by `tools/analyze.py` from `results/*.csv`. Ratios are *allocator / graph coloring*.\n")

    # ---- C1
    P("## C1: compile time by phase (kernels, depth-first numbering)\n")
    P("Time to allocate registers for one function, split like the paper's Fig. 3: liveness analysis, "
      "allocation setup (intervals for linear scan, interference graph for coloring) and allocation proper. "
      "Means of 10 trials; R = 8. 'total' = the three phases. 'alloc-only' ignores liveness and setup.\n")
    P("| program | vars | blocks | live | LS setup | LS alloc | GC setup | GC alloc | total GC / LS | alloc-only GC / LS | setup GC / LS | noise (sd of totals) |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|")
    c1_total, c1_alloc = [], []
    for p in progs:
        l, c = K[(p, "linear", "depth", 8)], K[(p, "color", "depth", 8)]
        rt, ra, rs = c["total"] / l["total"], c["alloc"] / l["alloc"], c["setup"] / l["setup"]
        c1_total.append(rt); c1_alloc.append(ra)
        P(f"| {p} | {l['vars']} | {l['blocks']} | {fmt_t(l['live'])} | {fmt_t(l['setup'])} | {fmt_t(l['alloc'])} | "
          f"{fmt_t(c['setup'])} | {fmt_t(c['alloc'])} | {rt:.2f} | {ra:.2f} | {rs:.2f} | "
          f"LS {100 * l['total_sd'] / l['total']:.0f}%, GC {100 * c['total_sd'] / c['total']:.0f}% |")
    P(f"\nGeometric mean over the kernels: total GC/LS = **{geomean(c1_total):.2f}**, alloc-only GC/LS = **{geomean(c1_alloc):.2f}**. "
      f"Linear scan is faster in total on {sum(r > 1 for r in c1_total)} of {len(progs)} kernels and in allocation proper on {sum(r > 1 for r in c1_alloc)} of {len(progs)}.\n")

    # ---- C4 / C5
    P("## C4, C5: code quality (kernels)\n")
    P("Executed VM instructions (spill loads and stores included) relative to graph coloring, depth-first numbering. "
      "The paper's Table II reports run time relative to coloring; this is our analogue. "
      "'LS' = linear scan (end-point spill choice), 'U' = usage-count.\n")
    for metric, label in (("executed", "executed instructions"), ("cycles", "weighted cycles (load/store cost 3, others 1)")):
        P(f"### {label}: ratio to graph coloring\n")
        P("| program | " + " | ".join(f"LS R={R} | U R={R}" for R in Rs) + " |")
        P("|---|" + "---|---|" * len(Rs))
        ls_all = defaultdict(list); u_all = defaultdict(list)
        for p in progs:
            cells = []
            for R in Rs:
                c = K[(p, "color", "depth", R)][metric]
                l = K[(p, "linear", "depth", R)][metric] / c
                u = K[(p, "usage", "depth", R)][metric] / c
                ls_all[R].append(l); u_all[R].append(u)
                cells += [f"{l:.2f}", f"{u:.2f}"]
            P(f"| {p} | " + " | ".join(cells) + " |")
        P("| **geomean** | " + " | ".join(f"**{geomean(ls_all[R]):.2f}** | **{geomean(u_all[R]):.2f}**" for R in Rs) + " |")
        P("")
        if metric == "executed":
            within = {R: sum(x <= 1.12 for x in ls_all[R]) for R in Rs}
            P("Linear scan within 12% of coloring on: " + ", ".join(f"R={R}: {within[R]}/{len(progs)}" for R in Rs) + " kernels.\n")
            for R in Rs:
                worst = sorted(((x, p) for x, p in zip(ls_all[R], progs)), reverse=True)[:3]
                P(f"- R={R} largest LS/GC: " + ", ".join(f"{p} {x:.2f}" for x, p in worst))
            P("")
            P("Against the *better* of the two colorings on each program (weight, weight/degree), so the baseline is not one unlucky heuristic:\n")
            P("| | " + " | ".join(f"R={R}" for R in Rs) + " |")
            P("|---|" + "---|" * len(Rs))
            for label, alloc in (("LS / best GC (geomean)", "linear"), ("U / best GC (geomean)", "usage")):
                cells = []
                for R in Rs:
                    rr = [K[(p, alloc, "depth", R)]["executed"] / min(K[(p, "color", "depth", R)]["executed"], K[(p, "color-ratio", "depth", R)]["executed"]) for p in progs]
                    cells.append(f"{geomean(rr):.2f} (max {max(rr):.2f}, within 12%: {sum(x <= 1.12 for x in rr)}/{len(progs)})")
                P(f"| {label} | " + " | ".join(cells) + " |")
            P("")
            P("Usage-count relative to coloring, same runs: " + ", ".join(f"R={R}: min {min(u_all[R]):.2f}, max {max(u_all[R]):.2f}" for R in Rs) + ".\n")

    # ---- C6
    P("## C6: depth-first versus layout numbering (kernels)\n")
    P("Linear scan only (graph coloring and usage-count do not use the numbering). Executed instructions, layout / depth-first.\n")
    P("| program | " + " | ".join(f"R={R}" for R in Rs) + " |")
    P("|---|" + "---|" * len(Rs))
    nums_all = defaultdict(list)
    differing = 0
    for p in progs:
        cells = []
        for R in Rs:
            r = K[(p, "linear", "layout", R)]["executed"] / K[(p, "linear", "depth", R)]["executed"]
            nums_all[R].append(r)
            differing += abs(r - 1) > 1e-12
            cells.append(f"{r:.3f}")
        P(f"| {p} | " + " | ".join(cells) + " |")
    allv = [x for R in Rs for x in nums_all[R]]
    P(f"\nOf {len(allv)} program x R cells, layout differs from depth-first in {differing}; "
      f"the extremes are {min(allv):.3f} and {max(allv):.3f}; geometric mean {geomean(allv):.3f}.\n")

    # ---- C7
    P("## C7: spill heuristic, end-point (interval length) versus usage count (interval weight)\n")
    P("Linear scan, depth-first numbering. Executed instructions, weight-heuristic / end-point heuristic (below 1 means weight is better).\n")
    P("| program | " + " | ".join(f"R={R}" for R in Rs) + " |")
    P("|---|" + "---|" * len(Rs))
    w_all = defaultdict(list)
    for p in progs:
        cells = []
        for R in Rs:
            r = K[(p, "linear-weight", "depth", R)]["executed"] / K[(p, "linear", "depth", R)]["executed"]
            w_all[R].append(r)
            cells.append(f"{r:.2f}")
        P(f"| {p} | " + " | ".join(cells) + " |")
    P("| **geomean** | " + " | ".join(f"**{geomean(w_all[R]):.2f}**" for R in Rs) + " |")
    P("")
    P("Static spill counts, linear scan (end-point) / linear scan (weight) / coloring / coloring (weight per degree), R = 8:\n")
    P("| program | vars | LS | LS-w | GC | GC-r |")
    P("|---|---|---|---|---|---|")
    for p in progs:
        row = [K[(p, a, "depth", 8)]["spills"] for a in ("linear", "linear-weight", "color", "color-ratio")]
        P(f"| {p} | {K[(p, 'linear', 'depth', 8)]['vars']} | " + " | ".join(map(str, row)) + " |")
    P("")

    # ------------------------------------------------------------------ pathological (a)
    A = group(load("path_a.csv"))
    ns = sorted({k[0] for k in A}, key=lambda s: int(s.split("_")[-1]))
    nvals = [int(s.split("_")[-1]) for s in ns]
    P("## C2: type (a), n simultaneously live variables (R = 16)\n")
    P("| n | LS total | GC total | GC / LS total | LS alloc | GC alloc | GC / LS alloc | spills LS | spills GC | executed LS | executed GC |")
    P("|---|---|---|---|---|---|---|---|---|---|---|")
    ls_t, gc_t, ls_a, gc_a = [], [], [], []
    same_spills = True
    for s, n in zip(ns, nvals):
        l, c = A[(s, "linear", "depth", 16)], A[(s, "color", "depth", 16)]
        ls_t.append(l["total"]); gc_t.append(c["total"]); ls_a.append(l["alloc"]); gc_a.append(c["alloc"])
        same_spills &= l["spills"] == c["spills"]
        P(f"| {n} | {fmt_t(l['total'])} | {fmt_t(c['total'])} | {c['total'] / l['total']:.1f} | {fmt_t(l['alloc'])} | {fmt_t(c['alloc'])} | "
          f"{c['alloc'] / l['alloc']:.1f} | {l['spills']} | {c['spills']} | {l['executed']} | {c['executed']} |")
    big = [i for i, n in enumerate(nvals) if n >= 32]
    xs = [nvals[i] for i in big]
    P(f"\nLog-log slopes for n >= 32: linear scan total **{slope(xs, [ls_t[i] for i in big]):.2f}**, "
      f"graph coloring total **{slope(xs, [gc_t[i] for i in big]):.2f}**, linear scan alloc-only {slope(xs, [ls_a[i] for i in big]):.2f}, "
      f"graph coloring alloc-only {slope(xs, [gc_a[i] for i in big]):.2f}.")
    i512 = nvals.index(512)
    P(f"At n = 512: total GC/LS = **{gc_t[i512] / ls_t[i512]:.1f}x**, allocation-only GC/LS = **{gc_a[i512] / ls_a[i512]:.1f}x**. "
      f"Spill counts identical at every n: **{same_spills}**.\n")
    # where the cost goes for GC at 512
    c = A[(ns[i512], "color", "depth", 16)]
    P(f"Graph coloring at n = 512 splits as liveness {fmt_t(c['live'])}, interference graph {fmt_t(c['setup'])}, coloring {fmt_t(c['alloc'])}.\n")

    fig, ax = plt.subplots(figsize=(6, 4.2))
    ax.loglog(nvals, [t / 1e9 for t in gc_t], "o-", label="Graph coloring")
    ax.loglog(nvals, [t / 1e9 for t in ls_t], "s-", label="Linear scan")
    ax.set_xlabel("n (simultaneously live variables)")
    ax.set_ylabel("allocation time (s): liveness + setup + allocation")
    ax.set_title("Type (a): analogue of the paper's Fig. 5")
    ax.legend(); ax.grid(True, which="both", alpha=0.3)
    fig.tight_layout(); fig.savefig(os.path.join(RES, "fig5_analogue.png"), dpi=140); plt.close(fig)

    # ------------------------------------------------------------------ pathological (b)
    for csvname, tag, title in (("path_b.csv", "path_b", "pure staggered intervals (our reading of Fig. 4(b))"),
                                ("path_bacc.csv", "path_bacc", "the same window plus a long-lived accumulator")):
        B = group(load(csvname))
        ms = sorted({int(k[0].split("_")[-1]) for k in B})
        ks = sorted({int(k[0].split("_")[-2]) for k in B})
        P(f"## C3: type (b), {title}; k sets, at most m live at once (R = 16)\n")
        P("| m | k | vars | LS total | GC total | GC / LS | spills LS / LS-w / GC / GC-r | executed LS / LS-w / GC / GC-r |")
        P("|---|---|---|---|---|---|---|---|")
        fig, ax = plt.subplots(figsize=(6.4, 4.4))
        sl_rows = []
        same_b = True
        for m in ms:
            lt, gt = [], []
            for k in ks:
                sname = f"{tag}_{k}_{m}"
                g = {a: B[(sname, a, "depth", 16)] for a in ("linear", "linear-weight", "color", "color-ratio")}
                l, c = g["linear"], g["color"]
                lt.append(l["total"]); gt.append(c["total"])
                same_b &= l["spills"] == c["spills"]
                sp = " / ".join(str(g[a]["spills"]) for a in g)
                ex = " / ".join(str(g[a]["executed"]) for a in g)
                P(f"| {m} | {k} | {l['vars']} | {fmt_t(l['total'])} | {fmt_t(c['total'])} | {c['total'] / l['total']:.1f} | {sp} | {ex} |")
            sl_rows.append((m, slope(ks, lt), slope(ks, gt), gt[-1] / lt[-1]))
            ax.loglog(ks, [t / 1e9 for t in gt], "o-", label=f"Graph coloring (m={m})")
            ax.loglog(ks, [t / 1e9 for t in lt], "s--", label=f"Linear scan (m={m})")
        ax.set_xlabel("k (successive sets)"); ax.set_ylabel("allocation time (s)")
        ax.set_title(f"Type (b), {tag.replace('path_', '')}: analogue of Fig. 6")
        ax.legend(fontsize=6, ncol=2); ax.grid(True, which="both", alpha=0.3)
        fig.tight_layout(); fig.savefig(os.path.join(RES, f"fig6_analogue_{tag.replace('path_', '')}.png"), dpi=140); plt.close(fig)
        P("\nLog-log slope of total time against k, per m, and the GC/LS ratio at the largest k:\n")
        P("| m | LS slope | GC slope | GC/LS at k = " + str(ks[-1]) + " |")
        P("|---|---|---|---|")
        for m, a, b, r in sl_rows:
            P(f"| {m} | {a:.2f} | {b:.2f} | {r:.1f} |")
        kk = ks[-1]
        P("\nVertical spacing between curves at k = " + str(kk) + " (time at m / time at the smallest m):\n")
        P("| m | LS | GC |")
        P("|---|---|---|")
        l0 = B[(f"{tag}_{kk}_{ms[0]}", "linear", "depth", 16)]["total"]
        g0 = B[(f"{tag}_{kk}_{ms[0]}", "color", "depth", 16)]["total"]
        for m in ms:
            l = B[(f"{tag}_{kk}_{m}", "linear", "depth", 16)]["total"]
            c = B[(f"{tag}_{kk}_{m}", "color", "depth", 16)]["total"]
            P(f"| {m} | {l / l0:.1f} | {c / g0:.1f} |")
        P(f"\nSpill counts of linear scan and coloring identical at every (k, m): **{same_b}**.\n")

    with open(os.path.join(RES, "summary.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
